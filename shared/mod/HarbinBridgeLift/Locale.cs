                ? "按 ModsData\\HarbinBridgeLift\\rail_station.json 放火车站：预制件按运行时名字解析，定义实体 = CreationDefinition+ObjectDefinition+Updated 排进 ToolOutputBarrier，applyMode 走 Clear→None→（等 Temp）→Apply。5 秒后还原原工具，按「本轮标记/临时实体/永久建筑」分类自查，报告位置/朝向/离最近轨道中线距离。重复点会先清掉本会话上次放的站（幂等重放）。报告：last_station_test.txt。"
                : "Places train stations from rail_station.json via the object branch (ObjectDefinition + E2C handshake), then classified self-check incl. position/yaw/distance-to-track. Re-clicking replaces this session's placement. Report: last_station_test.txt.";

            d[m_Setting.GetOptionLabelLocaleID(nameof(Setting.PlaceStationRoad))] = m_Zh
                ? "⑨ 站前路（Small Road + 两端挂既有道路节点）"
